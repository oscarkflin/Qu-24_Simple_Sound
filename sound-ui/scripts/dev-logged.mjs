import {spawn} from 'node:child_process';
import {createWriteStream,mkdirSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';
const root=fileURLToPath(new URL('../',import.meta.url));
const logDir=resolve(root,'logs');mkdirSync(logDir,{recursive:true});
const filename=resolve(logDir,`host-${new Date().toISOString().replace(/[:.]/g,'-')}.log`);
const log=createWriteStream(filename,{flags:'wx'});
let bytes=0,capped=false;
const write=(kind,text)=>{if(capped)return;const clean=String(text).replace(/\x1b\[[0-9;]*m/g,'');const line=`${new Date().toISOString()} [${kind}] ${clean}`;bytes+=Buffer.byteLength(line);if(bytes>4*1024*1024){capped=true;log.write('\nLog reached 4 MB. Recording stopped; host continues.\n');return;}log.write(line);};
log.on('error',e=>{console.error('Host log unavailable:',e.message);capped=true;});
console.log(`Host diagnostics: ${filename}`);
write('start',`Node ${process.version}; platform ${process.platform}; UI preview only\n`);
const child=spawn(process.execPath,[resolve(root,'node_modules/vinext/dist/cli.js'),'dev','--host','0.0.0.0',...process.argv.slice(2)],{cwd:root,stdio:['inherit','pipe','pipe']});
child.stdout.on('data',d=>{process.stdout.write(d);write('stdout',d);});
child.stderr.on('data',d=>{process.stderr.write(d);write('stderr',d);});
child.on('error',e=>{write('error',e.stack||e.message);log.end();process.exitCode=1;});
child.on('exit',(code,signal)=>{write('exit',`code=${code} signal=${signal}\n`);log.end();process.exitCode=code??0;});
process.on('SIGINT',()=>child.kill('SIGINT'));
process.on('SIGTERM',()=>child.kill('SIGTERM'));
